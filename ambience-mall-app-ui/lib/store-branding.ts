// ---------------------------------------------------------------------------------------------
// Helper: Extract clean monogram & matching key
// ---------------------------------------------------------------------------------------------

function cleanKey(rawName: string): string {
  return rawName.toLowerCase().replace(/['"’]/g, '').trim()
}

function extractMonogram(name: string): string {
  const words = name
    .replace(/[^a-zA-Z0-9\s]/g, ' ')
    .trim()
    .split(/\s+/)
    .filter(Boolean)

  if (words.length === 0) return 'AM'
  if (words.length === 1) {
    const w = words[0]
    return w.length >= 2 ? w.slice(0, 2).toUpperCase() : w.toUpperCase()
  }
  return (words[0][0] + words[1][0]).toUpperCase()
}

// Hash-based deterministic color generator for uncommon boutiques
function stringToColor(str: string): { bg: string; grad: string; accent: string } {
  let hash = 0
  for (let i = 0; i < str.length; i++) {
    hash = str.charCodeAt(i) + ((hash << 5) - hash)
  }
  const h1 = Math.abs(hash) % 360
  const h2 = (h1 + 35) % 360
  const bg = `hsl(${h1}, 65%, 26%)`
  const grad = `linear-gradient(135deg, hsl(${h1}, 70%, 30%) 0%, hsl(${h2}, 75%, 18%) 100%)`
  const accent = `hsl(${(h1 + 60) % 360}, 85%, 65%)`
  return { bg, grad, accent }
}

// ---------------------------------------------------------------------------------------------
// Main Function: getStoreBranding
// ---------------------------------------------------------------------------------------------

export function getStoreBranding(store: { name: string; category?: string; id?: string }): BrandBranding {
  const rawName = store.name || 'Store'
  const key = cleanKey(rawName)
  const category = store.category || 'Fashion & Retail'

  // 1. Direct registry lookup
  if (BRAND_REGISTRY[key]) {
    const reg = BRAND_REGISTRY[key]
    return {
      name: reg.name || rawName,
      shortName: reg.shortName || rawName.slice(0, 14),
      monogram: reg.monogram || extractMonogram(rawName),
      bgColor: reg.bgColor || '#1A1A1A',
      bgGradient: reg.bgGradient || `linear-gradient(135deg, ${reg.bgColor || '#2A2A2A'} 0%, #000000 100%)`,
      textColor: reg.textColor || '#FFFFFF',
      accentColor: reg.accentColor || '#D4AF37',
      category: reg.category || category,
      iconType: reg.iconType || 'fashion',
      badgeType: reg.badgeType || 'circle',
      fontStyle: reg.fontStyle || 'sans',
    }
  }

  // 2. Partial substring matching against known brands
  for (const [regKey, reg] of Object.entries(BRAND_REGISTRY)) {
    if (key.includes(regKey) || regKey.includes(key)) {
      return {
        name: rawName,
        shortName: reg.shortName || rawName.slice(0, 14),
        monogram: reg.monogram || extractMonogram(rawName),
        bgColor: reg.bgColor || '#1A1A1A',
        bgGradient: reg.bgGradient,
        textColor: reg.textColor || '#FFFFFF',
        accentColor: reg.accentColor || '#D4AF37',
        category: reg.category || category,
        iconType: reg.iconType || 'fashion',
        badgeType: reg.badgeType || 'rounded',
        fontStyle: reg.fontStyle || 'sans',
      }
    }
  }

  // 3. Category-tailored fallback
  const catDefaults = CATEGORY_PALETTES[category] || CATEGORY_PALETTES['Fashion & Retail']
  const hashed = stringToColor(rawName)

  return {
    name: rawName,
    shortName: rawName.slice(0, 14),
    monogram: extractMonogram(rawName),
    bgColor: catDefaults.bg,
    bgGradient: catDefaults.grad,
    textColor: catDefaults.text,
    accentColor: catDefaults.accent || hashed.accent,
    category,
    iconType: catDefaults.icon,
    badgeType: 'rounded',
    fontStyle: 'sans',
  }
}
